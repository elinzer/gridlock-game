export const GLYPH_W = 5;
export const GLYPH_H = 7;
const ADVANCE = 6;

export function textWidth(str, scale = 1) {
  return str.length ? (str.length * ADVANCE - 1) * scale : 0;
}

export function drawText(ctx, str, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  for (let n = 0; n < str.length; n++) {
    const glyph = GLYPHS[str[n]] || GLYPHS['?'];
    const gx = x + n * ADVANCE * scale;
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = glyph[row];
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits[col] === '1') ctx.fillRect(gx + col * scale, y + row * scale, scale, scale);
      }
    }
  }
}

export function drawTextCentered(ctx, str, cx, y, color, scale = 1) {
  drawText(ctx, str, Math.round(cx - textWidth(str, scale) / 2), y, color, scale);
}
