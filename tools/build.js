import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import QRCode from 'qrcode';
import * as esbuild from 'esbuild';
import * as acorn from 'acorn';
import { LINKEDIN_URL } from '../src/config.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...parts) => join(root, ...parts);
const MAX_QR_SIZE = 29;

function writeQR() {
  const qr = QRCode.create(LINKEDIN_URL, { errorCorrectionLevel: 'L' });
  const size = qr.modules.size;
  if (size > MAX_QR_SIZE) {
    throw new Error(`QR code is ${size}x${size}; must be <= ${MAX_QR_SIZE}. Shorten LINKEDIN_URL.`);
  }
  const modules = Array.from(qr.modules.data, (v) => (v ? 1 : 0));
  mkdirSync(p('src/generated'), { recursive: true });
  writeFileSync(
    p('src/generated/qr.js'),
    `// Generated by tools/build.js. Do not edit.\nexport const QR = ${JSON.stringify({ size, modules })};\n`
  );
}

async function bundle() {
  const result = await esbuild.build({
    entryPoints: [p('src/main.js')],
    bundle: true,
    format: 'iife',
    target: 'safari12',
    minify: true,
    write: false,
    logLevel: 'silent',
  });
  const code = result.outputFiles[0].text;
  acorn.parse(code, { ecmaVersion: 2018 });
  return code;
}

async function main() {
  writeQR();
  const code = (await bundle()).replace(/<\/script/gi, '<\\/script');
  const template = readFileSync(p('web/index.template.html'), 'utf8');
  const html = template.replace('<!--BUNDLE-->', () => code);
  const version = createHash('sha256').update(html).digest('hex').slice(0, 10);
  mkdirSync(p('dist'), { recursive: true });
  writeFileSync(p('dist/index.html'), html);
  const sw = readFileSync(p('web/sw.js'), 'utf8').replace(/__CACHE_VERSION__/g, version);
  writeFileSync(p('dist/sw.js'), sw);
  console.log(`built dist/index.html (${(html.length / 1024).toFixed(1)} KB), cache ${version}`);
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
